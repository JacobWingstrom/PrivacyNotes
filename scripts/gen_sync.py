"""Generates Hush/Sync/SyncModels.generated.swift from the @Model classes.
Run from the repo root: python3 -I <this> [--types]"""
import re, sys, os

FILES = ['Hush/Models/Note.swift', 'Hush/Models/Models.swift', 'Hush/Models/BoardModels.swift', 'Hush/Models/HomelabModels.swift']
PROP = re.compile(r'^    (@Attribute\(\.externalStorage\) )?var (\w+): ([^={]+?) = (.+)$')

# Fields sealed with this iPhone's own key: sent decrypted inside the sync envelope
# (which is encrypted with the sync key) and re-sealed with the local key on arrival.
SEALED = {('Note', 'lockedBody'), ('VaultItem', 'sealedMeta'), ('VaultItem', 'sealedImage'), ('StoredFile', 'sealedData')}

# Stable, platform-neutral type names used on the wire.
TYPE_NAMES = {
    'Note': 'note', 'TaskItem': 'task', 'CalendarEvent': 'event', 'JournalEntry': 'journal', 'Drawing': 'drawing',
    'VaultItem': 'vault', 'StoredFile': 'file', 'Contact': 'contact', 'Bookmark': 'bookmark', 'Folder': 'folder',
    'NoteVersion': 'noteVersion', 'NoteTemplate': 'template', 'Habit': 'habit',
    'LabDevice': 'labDevice', 'LabService': 'labService', 'LabSubnet': 'labSubnet', 'LabRack': 'labRack',
    'LabLink': 'labLink', 'LabDiagram': 'labDiagram', 'Runbook': 'runbook', 'ComposeStack': 'composeStack',
    'Board': 'board', 'BoardCard': 'boardCard',
}

NEW = {
    'BoardCard': 'BoardCard(boardID: UUID(), columnID: UUID())', 'LabLink': 'LabLink(from: UUID(), to: UUID())',
    'VaultItem': 'VaultItem(kind: .note)', 'StoredFile': 'StoredFile(name: "", typeIdentifier: "", data: Data())',
    'Folder': 'Folder(name: "")', 'NoteVersion': 'NoteVersion(noteID: UUID(), title: "", body: "")',
    'NoteTemplate': 'NoteTemplate(name: "", emoji: "", title: "", body: "")',
}

def parse():
    models = []
    for path in FILES:
        lines = open(path).read().split('\n')
        i = 0
        while i < len(lines):
            if lines[i].strip() == '@Model':
                m = re.match(r'^(?:final )?class (\w+)', lines[i + 1].strip())
                name = m.group(1)
                props = []
                j = i + 2
                while j < len(lines) and lines[j] != '}':
                    p = PROP.match(lines[j])
                    if p:
                        props.append((p.group(2), p.group(3).strip(), bool(p.group(1))))
                    j += 1
                models.append((name, props))
                i = j
            i += 1
    return models

def enc(model, name, typ, external):
    opt = typ.endswith('?')
    base = typ[:-1] if opt else typ
    if (model, name) in SEALED:
        if external:
            return f'e.blob("{name}", {name}, sealed: true)'
        return f'e.sealed("{name}", {name})'
    if external:
        return f'e.blob("{name}", {name}, sealed: false)'
    fn = {'String': 'string', 'Int': 'int', 'Double': 'double', 'Bool': 'bool', 'Date': 'date', 'UUID': 'uuid',
          'Data': 'data', '[String]': 'strings', '[UUID]': 'uuids'}.get(base)
    if fn is None:
        raise SystemExit(f'unsupported type {model}.{name}: {typ}')
    return f'e.{fn}("{name}", {name})'

def dec(model, name, typ, external):
    opt = typ.endswith('?')
    base = typ[:-1] if opt else typ
    if (model, name) in SEALED and not external:
        return f'if let v = d.sealed("{name}") {{ {name} = v }}'
    if (model, name) in SEALED or external:
        sealed = 'true' if (model, name) in SEALED else 'false'
        if opt:
            return f'if d.has("{name}") {{ {name} = d.optionalBlob("{name}", sealed: {sealed}) }}'
        return f'if let v = d.blob("{name}", sealed: {sealed}) {{ {name} = v }}'
    fn = {'String': 'string', 'Int': 'int', 'Double': 'double', 'Bool': 'bool', 'Date': 'date', 'UUID': 'uuid',
          'Data': 'data', '[String]': 'strings', '[UUID]': 'uuids'}[base]
    if opt:
        return f'if d.has("{name}") {{ {name} = d.{fn}("{name}") }}'
    return f'if let v = d.{fn}("{name}") {{ {name} = v }}'

def main():
    models = parse()
    if '--types' in sys.argv:
        for n, ps in models:
            print(n, [(p, t) for p, t, _ in ps])
        return
    out = ['// GENERATED by scripts/gen_sync.py from the @Model classes. Do not edit by hand.',
           '// Field names and value encodings are the cross-platform sync format; see docs/sync-protocol.md.',
           'import Foundation', 'import SwiftData', '']
    for n, ps in models:
        if n not in TYPE_NAMES:
            raise SystemExit(f'add a wire name for {n}')
        if not any(p == 'id' for p, _, _ in ps):
            raise SystemExit(f'{n} has no id')
        out.append(f'extension {n}: SyncModel {{')
        out.append(f'    static var syncType: String {{ "{TYPE_NAMES[n]}" }}')
        out.append('    var syncID: UUID { id }')
        out.append('    func syncSetID(_ newID: UUID) { id = newID }')
        out.append(f'    static func syncNew() -> {n} {{ {NEW.get(n, n + "()")} }}')
        out.append('    func syncEncode(_ e: SyncEncoder) {')
        for p, t, x in ps:
            if p == 'id': continue
            out.append('        ' + enc(n, p, t, x))
        out.append('    }')
        out.append('    func syncDecode(_ d: SyncDecoder) {')
        for p, t, x in ps:
            if p == 'id': continue
            out.append('        ' + dec(n, p, t, x))
        out.append('    }')
        out.append('}')
        out.append('')
    out.append('enum SyncRegistry {')
    out.append('    static let models: [any SyncModel.Type] = [')
    out.append('        ' + ', '.join(f'{n}.self' for n, _ in models) + ',')
    out.append('    ]')
    out.append('}')
    os.makedirs('Hush/Sync', exist_ok=True)
    open('Hush/Sync/SyncModels.generated.swift', 'w').write('\n'.join(out) + '\n')
    print('generated', len(models), 'models')

main()
